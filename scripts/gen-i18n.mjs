// 把 shell/i18n/zh-CN.tsv 生成为上游 localization 的简体中文语言包补丁
// shell/patches/soundcraft-zh-cn.patch（给上游 localization.rs 加 Chinese 变体 + zh-CN 表）。
//
// 背景：上游 soundcraft 自 2026-11 起自带 localization 模块（crates/ui-egui/src/localization.rs，
// English + pt-BR 静态表，字符串原样包裹在 crate::localization::text / localized_format! 里），
// 插件旧的自研 i18n 补丁（tr() 包裹）已弃用。这里只做「给上游加一门语言」：
//
//   1. 读 shell/i18n/zh-CN.tsv（英文 <Tab> 译文 [Tab> 上下文]，上下文列已随旧机制废弃，忽略）；
//   2. 生成 crates/ui-egui/locales/zh-CN/mod.rs（与 pt-BR 同构：translate() match + 空 ERROR_TEMPLATES）；
//   3. 对 crates/ui-egui/src/localization.rs 做 8 处定点修改（见 EDITS）；
//   4. 在 upstream/ 里用 git 生成补丁写入 shell/patches/soundcraft-zh-cn.patch，然后还原 upstream/。
//
// 改完 TSV 跑 `node scripts/gen-i18n.mjs`，再 `node scripts/fetch-upstream.mjs --force` 重放全部补丁。
// 上游同步后若 localization.rs 锚点漂移，本脚本会直接报错 —— 按 EDITS 里的锚点重新对位。
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "shell", "i18n", "zh-CN.tsv");
const patchOut = join(root, "shell", "patches", "soundcraft-zh-cn.patch");
const upstream = join(root, "upstream");
const locRs = join(upstream, "crates", "ui-egui", "src", "localization.rs");
const zhMod = join(upstream, "crates", "ui-egui", "locales", "zh-CN", "mod.rs");

// TSV → 条目。一行两列（英文 <Tab> 译文）或三列（第三列旧上下文机制遗留，忽略）。
const seen = new Map();
for (const raw of readFileSync(src, "utf8").split(/\r?\n/)) {
  const line = raw.replace(/\s+$/, "");
  if (!line.trim() || line.startsWith("#")) continue;
  const parts = line.split("\t");
  if (parts.length < 2 || parts.length > 3) {
    throw new Error(`zh-CN.tsv: 需要 2 或 3 个制表符分隔字段：${raw}`);
  }
  const [en, zh] = parts;
  if (!en || !zh) throw new Error(`zh-CN.tsv: 空字段：${raw}`);
  if (seen.has(en) && seen.get(en) !== zh) {
    throw new Error(`zh-CN.tsv: 「${en}」有两条不同的译文`);
  }
  seen.set(en, zh);
}
const rows = [...seen].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

// 控制字符转 \u{..}：键里可能有不可见字节，落进 .rs 源码太脆。
const esc = (s) =>
  s
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/[\u0000-\u001f\u007f]/g, (c) => `\\u{${c.codePointAt(0).toString(16)}}`);

const zhModule = [
  "/// Returns the Simplified Chinese translation for a source-language UI string.",
  "/// Generated by the OTools plugin from `shell/i18n/zh-CN.tsv` (scripts/gen-i18n.mjs); do not edit.",
  "pub(super) fn translate(source: &str) -> Option<&'static str> {",
  "    Some(match source {",
  ...rows.map(([en, zh]) => `        "${esc(en)}" => "${esc(zh)}",`),
  "        // 查无此串回落英文（zh-CN 没有 menu_translate 的运行时模板层）。",
  "        _ => return None,",
  "    })",
  "}",
  "",
  "/// Simplified Chinese has no engine-error templates yet; low-level errors stay in English.",
  "pub(super) static ERROR_TEMPLATES: &[(&str, &str)] = &[];",
  "",
].join("\n");

// localization.rs 的定点修改：锚点在上游漂移时立刻报错，而不是静默打出错误补丁。
const EDITS = [
  {
    from: 'mod pt_br;\n',
    to: 'mod pt_br;\n\n#[path = "../locales/zh-CN/mod.rs"]\nmod zh_cn;\n',
  },
  {
    from: '    #[serde(rename = "pt-BR")]\n    PortugueseBrazil,\n}',
    to: '    #[serde(rename = "pt-BR")]\n    PortugueseBrazil,\n    #[serde(rename = "zh-CN")]\n    Chinese,\n}',
  },
  {
    from: 'pub const ALL: [Self; 2] = [Self::English, Self::PortugueseBrazil];',
    to: 'pub const ALL: [Self; 3] = [Self::English, Self::PortugueseBrazil, Self::Chinese];',
  },
  {
    from: '            Self::PortugueseBrazil => "pt-BR",',
    to: '            Self::PortugueseBrazil => "pt-BR",\n            Self::Chinese => "zh-CN",',
  },
  {
    from: '            Self::PortugueseBrazil => "Portuguese (Brazil)",',
    to: '            Self::PortugueseBrazil => "Portuguese (Brazil)",\n            Self::Chinese => "简体中文",',
  },
  {
    from: '            Self::PortugueseBrazil => number.replace(\'.\', ","),',
    to: '            Self::PortugueseBrazil => number.replace(\'.\', ","),\n            Self::Chinese => number.to_owned(),',
  },
  {
    from: '            Self::PortugueseBrazil => pt_br::translate(source).unwrap_or(source),',
    to: '            Self::PortugueseBrazil => pt_br::translate(source).unwrap_or(source),\n            Self::Chinese => zh_cn::translate(source).unwrap_or(source),',
  },
  {
    from: '        Language::PortugueseBrazil => pt_br::ERROR_TEMPLATES,',
    to: '        Language::PortugueseBrazil => pt_br::ERROR_TEMPLATES,\n        Language::Chinese => zh_cn::ERROR_TEMPLATES,',
  },
];

const git = (args) => execFileSync("git", args, { cwd: upstream, encoding: "utf8" });

// upstream/ 工作区带着已应用的 otools 补丁；只动本补丁涉及的两个路径，
// 结束后原样还原，不影响工作区其余文件。
const locOriginal = readFileSync(locRs, "utf8");
try {
  let loc = locOriginal;
  for (const [i, edit] of EDITS.entries()) {
    if (!loc.includes(edit.from)) {
      throw new Error(`localization.rs 锚点 #${i} 找不到（上游已变动？）：${JSON.stringify(edit.from.slice(0, 60))}`);
    }
    if (loc.split(edit.from).length > 2) {
      throw new Error(`localization.rs 锚点 #${i} 不唯一：${JSON.stringify(edit.from.slice(0, 60))}`);
    }
    loc = loc.replace(edit.from, edit.to);
  }
  writeFileSync(locRs, loc);
  mkdirSync(dirname(zhMod), { recursive: true });
  writeFileSync(zhMod, zhModule);

  // 只暂存这两个路径生成补丁：HEAD 是 pinned commit，diff 即「本补丁的全部内容」。
  git(["add", "crates/ui-egui/src/localization.rs", "crates/ui-egui/locales/zh-CN/mod.rs"]);
  const patch = git(["diff", "--cached", "--", "crates/ui-egui/src/localization.rs", "crates/ui-egui/locales/zh-CN/mod.rs"]);
  if (!patch.includes("zh-CN/mod.rs") || !patch.includes("Chinese")) {
    throw new Error("生成的补丁缺 zh-CN 内容，拒绝写入");
  }
  writeFileSync(patchOut, patch);
} finally {
  git(["reset", "-q", "crates/ui-egui/src/localization.rs", "crates/ui-egui/locales/zh-CN/mod.rs"]);
  writeFileSync(locRs, locOriginal);
  rmSync(join(upstream, "crates", "ui-egui", "locales", "zh-CN"), { recursive: true, force: true });
}

console.log(`gen-i18n: ${rows.length} entries -> ${patchOut}`);
